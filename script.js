function getCurrentLessonIndex() {
  const now = new Date();
  const cur = now.getHours() * 60 + now.getMinutes();
  const times = getTimes();
  if (!times) return -1;
  for (let i = 0; i < times.length; i++) {
    const [sh, sm] = times[i].start.split(":").map(Number);
    const [eh, em] = times[i].end.split(":").map(Number);
    if (cur >= sh * 60 + sm && cur < eh * 60 + em) return i;
  }
  return -1;
}
function isToday() {
  const jsDay = new Date().getDay();
  return jsDay >= 1 && jsDay <= 5 && state.day === jsDay - 1;
}
function formatTime() {
  const now = new Date();
  const pad = (n) => String(n).padStart(2, "0");
  return `${pad(now.getHours())}:${pad(now.getMinutes())}:${pad(now.getSeconds())}`;
}
function getShiftLabel(shift) {
  if (shift === 1) return { text: "1 смена", cls: "shift-1" };
  if (shift === 2) return { text: "2 смена", cls: "shift-2" };
  if (shift === "s") return { text: "средняя", cls: "shift-s" };
  if (shift === "p1") return { text: "1 класс", cls: "shift-p1" };
  if (shift === "p2") return { text: "2 класс", cls: "shift-p2" };
  if (shift === "p3") return { text: "3 класс", cls: "shift-p3" };
  if (shift === "p4") return { text: "4 класс", cls: "shift-p4" };
  return { text: "—", cls: "" };
}
function formatDateForDay(dayIndex) {
  const now = new Date();
  const jsDay = now.getDay();
  const todayIdx = jsDay === 0 ? 4 : jsDay - 1;
  const diff = dayIndex - todayIdx;
  const targetDate = new Date(now);
  targetDate.setDate(now.getDate() + diff);
  const day = targetDate.getDate();
  const month = MONTHS_GEN[targetDate.getMonth()];
  return { name: DAYS[dayIndex], date: `${day} ${month}` };
}
function getWeekRange() {
  const now = new Date();
  const jsDay = now.getDay();
  const todayIdx = jsDay === 0 ? 4 : jsDay - 1;
  const monday = new Date(now);
  monday.setDate(now.getDate() - todayIdx);
  const friday = new Date(monday);
  friday.setDate(monday.getDate() + 4);
  const fmt = (d) => `${d.getDate()} ${MONTHS_GEN[d.getMonth()]}`;
  return `${fmt(monday)} – ${fmt(friday)}`;
}
function render() {
  const container = document.getElementById("scheduleContainer");
  const info = document.getElementById("currentLessonInfo");
  if (!state.grade || !state.letter) {
    container.innerHTML =
      '<div class="empty-message">Выберите класс и букву класса</div>';
    info.textContent = "";
    return;
  }
  const runningIdx = isToday() ? getCurrentLessonIndex() : -1;
  const data = getClassData();
  const shift = data.shift;
  const shiftLabel = getShiftLabel(shift);
  if (state.mode === "day") {
    renderDayView(container, data, runningIdx, shiftLabel);
  } else {
    renderWeekView(container, data, runningIdx, shiftLabel);
  }
  if (isToday() && runningIdx >= 0) {
    const lessons = data.days[state.day];
    if (lessons && lessons[runningIdx]) {
      const subj = lessons[runningIdx];
      const times = getTimes()[runningIdx];
      info.innerHTML = `🔔 Сейчас идёт: <b style="color:var(--primary-dark)">${subj}</b> (${times.start}–${times.end})`;
    } else {
      info.textContent = "☕ Перемена";
    }
  } else if (isToday() && runningIdx === -1) {
    const now = new Date();
    const cur = now.getHours() * 60 + now.getMinutes();
    const times = getTimes();
    const first = times[0].start.split(":").map(Number);
    const last = times[times.length - 1].end.split(":").map(Number);
    if (cur < first[0] * 60 + first[1])
      info.textContent = "⏳ Занятия ещё не начались";
    else if (cur >= last[0] * 60 + last[1])
      info.textContent = "✅ Сегодня занятия окончены";
    else info.textContent = "☕ Перемена";
  } else {
    info.textContent = "";
  }
}
function renderDayView(container, data, runningIdx, shiftLabel) {
  const lessons = data.days[state.day] || [];
  const dayInfo = formatDateForDay(state.day);
  const todayTag = isToday() ? '<span class="tag today">Сегодня</span>' : "";
  let html = `
<div class="schedule-title">
<span class="day-title">
<span class="day-name">${dayInfo.name}</span>
<span class="day-date">${dayInfo.date}</span>
</span>
<span class="tag">${state.grade}${state.letter} класс</span>
${state.profile ? `<span class="tag">${state.profile}</span>` : ""}
<span class="shift-badge ${shiftLabel.cls}">${shiftLabel.text}</span>
${todayTag}
</div>
<div class="table-wrap">
<table>
<thead>
<tr><th>№</th><th>Время</th><th>Предмет</th></tr>
</thead>
<tbody>
`;
  const times = getTimes();
  let hasAny = false;
  for (let i = 0; i < times.length; i++) {
    const t = times[i];
    const lesson = lessons[i];
    if (!lesson || lesson === "") continue;
    hasAny = true;
    const isRunning = i === runningIdx;
    html += `<tr class="${isRunning ? "running" : ""}">
<td class="lesson-num">${t.n}</td>
<td class="lesson-time">${t.start}<br>${t.end}</td>
<td>
<div class="lesson-cell">
<div class="lesson-name">${lesson}</div>
${isRunning ? '<div class="running-badge"><span class="dot"></span>Идёт</div>' : ""}
</div>
</td>
</tr>`;
  }
  if (!hasAny) {
    html += `<tr><td colspan="3" style="padding:30px;color:var(--text-soft);font-style:italic">Нет занятий в этот день</td></tr>`;
  }
  html += "</tbody></table></div>";
  container.innerHTML = html;
}
function renderWeekView(container, data, runningIdx, shiftLabel) {
  const weekRange = getWeekRange();
  let html = `
<div class="schedule-title">
<span class="day-title">
<span class="day-name">Неделя</span>
<span class="day-date">${weekRange}</span>
</span>
<span class="tag">${state.grade}${state.letter} класс</span>
${state.profile ? `<span class="tag">${state.profile}</span>` : ""}
<span class="shift-badge ${shiftLabel.cls}">${shiftLabel.text}</span>
</div>
<div class="week-view">
`;
  const times = getTimes();
  for (let d = 0; d < 5; d++) {
    const lessons = data.days[d] || [];
    const isTodayCard = isToday() && d === state.day;
    const hasRunning =
      isTodayCard && runningIdx >= 0 && runningIdx < lessons.length;
    const classes = ["day-card"];
    if (isTodayCard) classes.push("today");
    const dayInfo = formatDateForDay(d);
    html += `<div class="${classes.join(" ")}">
<h3>
<span class="day-header-left">
<span class="day-name">${dayInfo.name}</span>
<span class="day-date">${dayInfo.date}</span>
</span>
${isTodayCard ? '<span class="today-tag">Сегодня</span>' : ""}
</h3>`;
    let hasAny = false;
    lessons.forEach((lesson, i) => {
      if (!lesson || lesson === "") return;
      hasAny = true;
      const t = times[i];
      const isRunning = hasRunning && i === runningIdx;
      html += `<div class="day-lesson ${isRunning ? "running" : ""}">
<div class="num">${t.n}</div>
<div class="info">
<div class="name">
${lesson}
${isRunning ? '<span class="running-mini"><span class="dot"></span>ИДЁТ</span>' : ""}
</div>
</div>
<div class="time">${t.start}<br>${t.end}</div>
</div>`;
    });
    if (!hasAny) {
      html += `<div style="color:var(--text-soft);font-style:italic;padding:10px 0;text-align:center">Нет занятий</div>`;
    }
    html += "</div>";
  }
  html += "</div>";
  container.innerHTML = html;
}
